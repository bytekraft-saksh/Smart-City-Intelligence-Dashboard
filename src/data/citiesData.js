export const getCityById = (id) => citiesData.find(city => city.id === id);

export const getAllCities = () => citiesData;

export const getComparisonData = (cityIds, metricKeys) => {
  const selectedCities = citiesData.filter(city => cityIds.includes(city.id));
  return selectedCities.map(city => {
    const data = { name: city.city_name, id: city.id };
    metricKeys.forEach(key => {
      data[key] = city[key];
    });
    return data;
  });
};

export const calculateCityRankings = (metricKey, lowerIsBetter = false) => {
  const sorted = [...citiesData].sort((a, b) => {
    if (lowerIsBetter) {
      return a[metricKey] - b[metricKey];
    }
    return b[metricKey] - a[metricKey];
  });
  return sorted.map((city, index) => ({
    rank: index + 1,
    city: city.city_name,
    value: city[metricKey],
    id: city.id
  }));
};
